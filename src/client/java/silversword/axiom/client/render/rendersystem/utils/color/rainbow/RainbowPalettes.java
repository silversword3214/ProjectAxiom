    public static RainbowPalette getByName(String name) {
        for (RainbowPalette p : ALL) {
            if (p.getName().equalsIgnoreCase(name)) return p;
        }
        return NEON;
    }

    /**
     * Ehdottaa palettia teeman accent-värin perusteella.
     * @param accentArgb Teeman accent-väri (ARGB)
     * @return paras osuma
     */
    public static RainbowPalette suggestFor(int accentArgb) {
        float[] hsv = new Color(accentArgb).toHsv();
        float hue = hsv[0];
        float sat = hsv[1];
        float val = hsv[2];

        // Tumma väri → DARK tai MIDNIGHT
        if (val < 0.25f) return MIDNIGHT;

        // Hyvin vaalea → LIGHT tai SILVER
        if (val > 0.9f && sat < 0.15f) return SILVER;
        if (sat < 0.12f) return MONOCHROME;

        // Vaalea pastelli → PASTEL/DREAM
        if (sat < 0.35f && val > 0.85f) {
            if (hue >= 180 && hue < 300) return DREAM;
            if (hue >= 300 || hue < 60)  return SAKURA;
            return PASTEL;
        }

        // Värikylläinen neon
        if (sat > 0.85f && val > 0.85f) {
            if (hue < 20 || hue >= 340) return NEON_PARTY;
            if (hue < 60)  return GOLD_RUSH;
            if (hue < 100) return MATRIX;
            if (hue < 160) return EMERALD;
            if (hue < 200) return CYBERPUNK;
            if (hue < 260) return SAPPHIRE;
            if (hue < 300) return GALAXY;
            return NEON;
        }

        // Hue-pohjainen valinta
        if (hue < 20 || hue >= 340) return RUBY;         // punainen
        if (hue < 40)  return VOLCANO;                    // oranssi-punainen
        if (hue < 55)  return AUTUMN;                     // oranssi
        if (hue < 70)  return GOLD_RUSH;                  // keltainen
        if (hue < 90)  return MINT;                       // keltavihreä
        if (hue < 140) return FOREST;                     // vihreä
        if (hue < 170) return EMERALD;                    // tummanvihreä
        if (hue < 190) return PEACOCK;                    // turkoosi
        if (hue < 210) return ICE;                        // vaalea syaani
        if (hue < 240) return OCEAN;                      // sininen
        if (hue < 260) return SAPPHIRE;                   // sininen
        if (hue < 280) return LAVENDER;                   // indigo
        if (hue < 300) return AMETHYST;                   // violetti
        if (hue < 320) return DRACULA;                    // magenta-violetti
        return CANDY;                                     // pinkki
    }
